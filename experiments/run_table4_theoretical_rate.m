%% ========================================================================
%  run_table4_theoretical_rate.m
%  Small table for Reviewer 3: observed decay of ||d_k||_F compared with
%  the theoretical R-linear rate factor theta^k.
%
%  The table uses curve-fitting Example 4.3, as suggested by the reviewer.
%  Since the constant C in the estimate
%      ||d_k||_F <= C theta^k ||d_0||_F
%  is an existence constant, the script reports the normalized observed decay
%      ||d_k||_F / ||d_0||_F = sqrt(E_k)
%  and the rate factor theta^k.
%
%  Run setup_paths.m once before this script, or run this script from any
%  location after adding the repository folders to the MATLAB path.
%  ========================================================================
clear; clc; close all;

%% ===== Settings =========================================================
p_deg   = 3;
tol_Ek  = 1e-6;
maxiter = 10000;

salspia_params.c     = 1e-4;   % GLL sufficient-decrease (sigma)
salspia_params.M     = 10;     % GLL memory length
salspia_params.delta = 1e-8;   % truncation threshold
salspia_params.eps_saf = 1e-30; % safeguard tolerance (Algorithm 1)

ex_id = 3;
m1    = 1000;                 % number of data points
n1    = 288;                  % number of control points
n     = n1 - 1;

%% ===== Build Example 4.3 ===============================================
script_dir = fileparts(mfilename('fullpath'));
repo_dir   = fileparts(script_dir);
addpath(fullfile(repo_dir, 'algorithms'));
addpath(fullfile(repo_dir, 'utils'));

Q = load(salspia_data('cur_data deer'));
if m1 ~= size(Q, 1)
    idx = round(linspace(1, size(Q, 1), m1));
    Q   = Q(idx, :);
end

[t, knots] = make_params_knots(Q, n, p_deg);
A          = build_collocation(knots, p_deg, t);
P0         = select_initial_ctrl_pts(Q, n);

%% ===== Run SaLSPIA and compute theta ===================================
[~, info_sl] = salspia(A, Q, P0, tol_Ek, maxiter, salspia_params);

H       = A' * A;
eigvals = sort(real(eig(H)));
eig_tol = max(1e-14, 1e-12 * max(eigvals));
eig_pos = eigvals(eigvals > eig_tol);

if isempty(eig_pos)
    error('No positive eigenvalue was detected for A''*A.');
end

lambda_min = eig_pos(1);
lambda_max = eig_pos(end);
Lambda_B   = max(sum(A, 1));
sigma      = salspia_params.c;
theta      = 1 - (1 - sigma) * lambda_min / Lambda_B;

%% ===== Prepare small table =============================================
Ek_hist = info_sl.Ek_history(:);
obs_decay = sqrt(Ek_hist);        % ||d_k||_F / ||d_0||_F

selected_k = [0, 5, 10, 15, 20, info_sl.iter_count];
selected_k = unique(selected_k(selected_k <= info_sl.iter_count), 'stable');
idx = selected_k + 1;             % MATLAB 1-based index

rate_factor = theta .^ selected_k;

T = table(selected_k(:), obs_decay(idx), rate_factor(:), ...
    'VariableNames', {'k', 'observed_norm_decay', 'theta_power_k'});

%% ===== Save outputs =====================================================
out_dir = fullfile(repo_dir, 'results', 'theoretical_rate_check');
if ~exist(out_dir, 'dir'), mkdir(out_dir); end

csv_file = fullfile(out_dir, 'rate_decay_example43.csv');
tex_file = fullfile(out_dir, 'rate_decay_example43.tex');
mat_file = fullfile(out_dir, 'rate_decay_example43.mat');

writetable(T, csv_file);
save(mat_file, 'T', 'theta', 'lambda_min', 'lambda_max', 'Lambda_B', ...
    'sigma', 'info_sl', 'ex_id', 'm1', 'n1');

fid = fopen(tex_file, 'w');
if fid < 0
    error('Cannot write %s', tex_file);
end

fprintf(fid, '%% Generated by experiments/run_table4_theoretical_rate.m\n');
fprintf(fid, '\\begin{table}[H]\n');
fprintf(fid, '\\centering\n');
fprintf(fid, '\\caption{Observed normalized decay of $\\|d_k\\|_F$ for SaLSPIA in Example~4.3. Since the constant $C$ in the theoretical estimate is an existence constant, the table reports the rate factor $\\theta^k$, where $\\theta=1-(1-\\sigma)\\lambda_{\\min}/\\Lambda_B$.}\n');
fprintf(fid, '\\label{tab:rate_decay_example43}\n');
fprintf(fid, '\\begin{tabular}{ccc}\n');
fprintf(fid, '\\hline\n');
fprintf(fid, '$k$ & $\\|d_k\\|_F/\\|d_0\\|_F$ & $\\theta^k$\\\\\n');
fprintf(fid, '\\hline\n');
for i = 1:numel(selected_k)
    fprintf(fid, '%d & %.3e & %.3e\\\\\n', ...
        selected_k(i), obs_decay(idx(i)), rate_factor(i));
end
fprintf(fid, '\\hline\n');
fprintf(fid, '\\end{tabular}\n');
fprintf(fid, '\\end{table}\n');
fclose(fid);

fprintf('\n============================================================\n');
fprintf('Theoretical-rate check for Example 4.3\n');
fprintf('============================================================\n');
fprintf('lambda_min = %.6e, lambda_max = %.6e, Lambda_B = %.6e\n', ...
    lambda_min, lambda_max, Lambda_B);
fprintf('theta = %.12f\n', theta);
fprintf('SaLSPIA iterations = %d, final E_k = %.3e\n\n', ...
    info_sl.iter_count, info_sl.Ek_history(end));
disp(T);
fprintf('\nSaved outputs to:\n  %s\n', out_dir);
